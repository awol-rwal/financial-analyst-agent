"""Readable investment-research style Word report, based on verified state.

No claim of recommendation, live market data, or primary-document review unless
those are genuinely present in source inputs.
"""

from pathlib import Path
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

from .workflow import WorkflowState


def _table(doc, headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Light Shading Accent 1"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, header in enumerate(headers):
        table.rows[0].cells[i].text = str(header)
    for values in rows:
        cells = table.add_row().cells
        for i, val in enumerate(values):
            cells[i].text = str(val)
    return table


def export_word(state: WorkflowState, destination: Path) -> Path:
    if state["status"] != "passed" or state.get("valuation") is None:
        raise ValueError("Cannot publish a blocked valuation")
    inp = state["input_data"]
    val = state["valuation"]
    history = state["financials"]
    analysis = state["analysis"]

    doc = Document()
    section = doc.sections[0]
    section.top_margin = Inches(0.72)
    section.bottom_margin = Inches(0.72)
    section.left_margin = Inches(0.83)
    section.right_margin = Inches(0.83)

    styles = doc.styles
    styles["Normal"].font.name = "Aptos"
    styles["Normal"].font.size = Pt(9)
    styles["Normal"].paragraph_format.space_after = Pt(6)
    for name in ("Title", "Heading 1", "Heading 2"):
        styles[name].font.name = "Aptos Display"
        styles[name].font.color.rgb = RGBColor(19, 37, 62)
    styles["Title"].font.size = Pt(23)
    styles["Heading 1"].font.size = Pt(13)

    doc.add_heading("Company valuation research", 0)
    line = doc.add_paragraph()
    line.add_run(f"{inp.company_name} ({inp.ticker})").bold = True
    line.add_run(f"   |   As of {inp.valuation_date:%d %B %Y}   |   {inp.currency}")
    if inp.is_synthetic_demo:
        demo = doc.add_paragraph("SYNTHETIC DEMONSTRATION — Not real company data or investment advice")
        demo.style = "Subtitle"
        for run in demo.runs:
            run.font.color.rgb = RGBColor(169, 56, 39)
            run.bold = True

    doc.add_heading("Executive summary", 1)
    doc.add_paragraph(state["report_summary"])
    if state.get("llm_summary"):
        doc.add_paragraph("Optional qualitative model critique: " + state["llm_summary"])

    doc.add_heading("DCF valuation", 1)
    _table(doc, ["Scenario", "WACC", "Terminal growth", f"Intrinsic value ({inp.currency}/share)"], [
        [key.title(), f"{res.wacc:.2%}", f"{res.terminal_growth:.2%}", f"{res.value_per_share:,.2f}"]
        for key, res in ((name, val.scenarios[name]) for name in ("bear", "base", "bull"))
    ])
    doc.add_paragraph(
        "Method: five-year or user-selected FCFF forecast; WACC = after-tax cost of debt and CAPM cost of "
        "equity; terminal value uses perpetual growth. Enterprise value is adjusted for latest available "
        "cash and debt, then divided by shares outstanding. These are modelled estimates, not market prices."
    )
    doc.add_heading("Historical financials", 1)
    _table(doc, ["FY", "Revenue", "EBIT", "D&A", "Capex", "NWC invest.", "Net cash"], [
        [y.year, f"{y.revenue:,.1f}", f"{y.ebit:,.1f}", f"{y.depreciation_amortization:,.1f}",
         f"{y.capex:,.1f}", f"{y.change_in_nwc:,.1f}", f"{y.cash-y.debt:,.1f}"]
        for y in history
    ])
    doc.add_paragraph(f"Units: {inp.currency} millions, except shares (millions). " + analysis.summary)

    doc.add_heading("Forecast reasoning", 1)
    doc.add_paragraph(analysis.reasoning)
    for name in ("bear", "base", "bull"):
        scenario = inp.scenarios[name]
        doc.add_heading(name.title() + " case", 2)
        doc.add_paragraph(scenario.reasoning)
        doc.add_paragraph(
            f"Revenue growth {scenario.revenue_growth:.1%} p.a.; EBIT margin {scenario.ebit_margin:.1%}; "
            f"capex/revenue {scenario.capex_as_pct_of_revenue:.1%}; "
            f"terminal growth {scenario.terminal_growth:.1%}. "
            f"Supporting evidence: {', '.join(scenario.supporting_evidence) or 'None provided'}."
        )
    doc.add_heading("Quality checks and limitations", 1)
    warnings = [f for f in state.get("findings", []) if f.severity == "warning"]
    if warnings:
        for finding in warnings:
            p = doc.add_paragraph(style="List Bullet")
            p.add_run(f"{finding.finding_id}: ").bold = True
            p.add_run(finding.finding)
    else:
        doc.add_paragraph("No validation warnings were generated by the configured checks.")
    doc.add_paragraph(
        "Qualitative assumptions may be wrong even when the DCF arithmetic reconciles. "
        "The workflow does not independently verify every source document; it checks registered "
        "provenance and mechanical consistency. This MVP does not include real-time prices, "
        "full filings reconciliation, comparable-company valuation, or company-specific risk adjustments."
    )
    doc.add_heading("Source register", 1)
    for source in state["sources"]:
        p = doc.add_paragraph(style="List Bullet")
        p.add_run(f"{source.source_id} — {source.title}. ").bold = True
        p.add_run(source.url)
    doc.add_paragraph("For machine-readable inputs, calculations and review findings, see run.json and the Excel audit sheets.")

    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.text = "Automated valuation research | Review source accuracy and assumptions before use"

    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    doc.save(destination)
    return destination
